#ifndef LLVM_LIB_TARGET_PIC16F1_MCTARGETDESC_PIC16F1INSTPRINTER_H
#define LLVM_LIB_TARGET_PIC16F1_MCTARGETDESC_PIC16F1INSTPRINTER_H

#include "llvm/MC/MCExpr.h"
#include "llvm/MC/MCInstPrinter.h"

namespace llvm {
class PIC16F1InstPrinter : public MCInstPrinter {
public:
  PIC16F1InstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                     const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  void printRegName(raw_ostream &O, MCRegister Reg) override;
  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;

  // Generated by TableGen.
  std::pair<const char *, uint64_t> getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg);

private:
  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printOperand(const MCInst *MI, uint64_t Address, unsigned OpNo,
                    raw_ostream &O) {
    printOperand(MI, OpNo, O);
  }
  void printFile(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printDest(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printFSR(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printIndMode(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printExprOperand(const MCExpr &E, raw_ostream &O);
};
} // namespace llvm

#endif
