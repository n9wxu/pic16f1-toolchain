#ifndef LLVM_LIB_TARGET_PIC16F1_GISEL_PIC16F1CALLLOWERING_H
#define LLVM_LIB_TARGET_PIC16F1_GISEL_PIC16F1CALLLOWERING_H

#include "llvm/CodeGen/CallingConvLower.h"
#include "llvm/CodeGen/GlobalISel/CallLowering.h"

namespace llvm {
class PIC16F1TargetLowering;

class PIC16F1CallLowering : public CallLowering {
public:
  explicit PIC16F1CallLowering(const PIC16F1TargetLowering &TLI);

  bool canLowerReturn(MachineFunction &MF, CallingConv::ID CallConv,
                      SmallVectorImpl<BaseArgInfo> &Outs,
                      bool IsVarArg) const override;
  bool lowerReturn(MachineIRBuilder &MIRBuilder, const Value *Val,
                   ArrayRef<Register> VRegs,
                   FunctionLoweringInfo &FLI) const override;
  bool lowerFormalArguments(MachineIRBuilder &MIRBuilder, const Function &F,
                            ArrayRef<ArrayRef<Register>> VRegs,
                            FunctionLoweringInfo &FLI) const override;
  bool lowerCall(MachineIRBuilder &MIRBuilder,
                 CallLoweringInfo &Info) const override;
};

} // namespace llvm

#endif
