#!/usr/bin/env python3
"""Generate the C device header and the linker script for one device.

Usage: gen_toolchain.py <devices/NAME.json> <include-dir> <lib-dir>
Every address and size comes from the device database.
"""
import json
import os
import re
import sys


def ident(name):
    return re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name) is not None


def gen_header(dev, path):
    name = dev["name"]
    guard = f"__{name}_H"
    src = dev["source"]
    sfr_names = {s["name"] for s in dev["sfrs"]} | {j["name"] for j in dev["joined_sfrs"]}
    out = [
        f"/* {name} special function registers.",
        f" * Generated by tools/devdb/gen_toolchain.py from {src['pack']} {src['version']},",
        f" * {src['file']}. Do not edit."
        + (f"\n * {src['imaginary']}" if src.get("imaginary") else "") + " */",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        "/* Bit-field views. These come first so that no register macro is",
        " * defined yet while the field names are declared. */",
    ]
    for s in dev["sfrs"]:
        fields = [f for f in s["fields"] if ident(f["name"]) and f["name"] not in sfr_names]
        if not fields or not ident(s["name"]):
            continue
        out.append("typedef union {")
        out.append("    unsigned char byte;")
        out.append("    struct {")
        bit = 0
        for f in sorted(fields, key=lambda f: f["bit"]):
            if f["bit"] < bit:
                continue  # overlapping alternative name
            if f["bit"] > bit:
                out.append(f"        unsigned char : {f['bit'] - bit};")
            out.append(f"        unsigned char {f['name']} : {f['width']};")
            bit = f["bit"] + f["width"]
        out.append("    };")
        out.append(f"}} {s['name']}bits_t;")
    out.append("")
    for s in dev["sfrs"]:
        if not ident(s["name"]):
            continue
        out.append(f"#define {s['name']} (*(volatile unsigned char *)0x{s['addr']:03X})")
        fields = [f for f in s["fields"] if ident(f["name"]) and f["name"] not in sfr_names]
        if fields:
            out.append(f"#define {s['name']}bits (*(volatile {s['name']}bits_t *)0x{s['addr']:03X})")
    out.append("")
    out.append("/* 16-bit register pairs, low byte first. */")
    for j in dev["joined_sfrs"]:
        if ident(j["name"]) and j["width"] == 16:
            out.append(f"#define {j['name']} (*(volatile unsigned int *)0x{j['addr']:03X})")
    out.append("")
    out.append("/* Configuration words. */")
    for c in dev["config"]:
        out.append(f"#define _{c['name']}_ADDR 0x{c['addr']:04X}")
        for f in c["fields"]:
            for vname, v in sorted(f.get("values", {}).items()):
                mask = ((1 << f["width"]) - 1) << f["bit"]
                word = (c["default"] & ~mask) | (v << f["bit"])
                out.append(f"#define _{c['name']}_{f['name']}_{vname} 0x{word:04X}")
    pins = sorted(dev.get("debug", {}).get("pins", {}).values())
    if pins:
        names = [n for p in pins for n in (p, f"LAT{p[1:]}", f"TRIS{p[1:]}")]
        out += [
            "",
            f"/* A program built for an in-circuit debugger (-mdebugger) leaves",
            f" * {' and '.join(pins)} to it: they are its clock and data lines. Naming",
            " * their port, latch or direction bits in such a build is an error. */",
            "#ifdef __DEBUG",
            "#pragma GCC poison " + " ".join(names),
            "#endif",
        ]
    out += ["", f"#endif /* {guard} */", ""]
    with open(path, "w") as f:
        f.write("\n".join(out))


def gen_config_table(dev, path):
    """The device's configuration settings, for the linker to make the
    configuration words from #pragma config (lld, Arch/PIC16F1.cpp, has the
    format)."""
    src = dev["source"]
    out = [f"# {dev['name']} configuration settings, for #pragma config.",
           f"# Generated by tools/devdb/gen_toolchain.py from {src['pack']} {src['version']}. Do not edit."]
    for c in dev["config"]:
        out.append(f"W {c['addr']:#x} {c['default']:#x}")
    uid = dev.get("user_id")
    if uid:
        for n, addr in enumerate(range(uid["begin"], uid["end"])):
            out.append(f"U {addr:#x} 0x3fff")
            out.append(f"S IDLOC{n} {addr:#x} 0x3fff")
    for c in dev["config"]:
        for f in c["fields"]:
            mask = ((1 << f["width"]) - 1) << f["bit"]
            out.append(f"S {f['name']} {c['addr']:#x} {mask:#x}")
            for vname, v in sorted(f.get("values", {}).items()):
                out.append(f"V {f['name']} {vname} {v << f['bit']:#x}")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")


def gen_ldscript(dev, path):
    name = dev["name"]
    src = dev["source"]
    words = dev["flash"]["words"]
    ram = dev["gpr_bytes"]
    stack = min(256, ram // 3)
    banks = dev["bank_count"]
    uid = dev.get("user_id")
    ee = dev.get("eeprom")
    extra_regions = extra_sections = ""
    if uid:
        extra_regions += f"\n  userid   (r)  : ORIGIN = {uid['begin'] * 2:#x}, LENGTH = {(uid['end'] - uid['begin']) * 2}"
        extra_sections += "\n  /* User ID words, from #pragma config IDLOCn. */\n  .userid : {{ KEEP(*(.userid)) }} > userid\n".replace("{{", "{").replace("}}", "}")
    if ee:
        extra_regions += f"\n  eeprom   (r)  : ORIGIN = {ee['hex_begin'] * 2:#x}, LENGTH = {ee['bytes'] * 2}"
        extra_sections += ("\n  /* Initial content of the data EEPROM (__EEPROM_DATA in <xc.h>): as in a"
                           "\n   * HEX file, a 16-bit word for each byte. */"
                           "\n  .eeprom : { KEEP(*(.eeprom .eeprom.*)) } > eeprom\n")
    cfg0 = min(c["addr"] for c in dev["config"])
    ncfg = len(dev["config"])
    # The RAM an in-circuit debugger's executive uses, if the device data
    # gives it and it is the end of RAM: a program linked for the debugger
    # (-mdebugger defines __debugger) ends its RAM below it.
    dbg = dev.get("debug", {}).get("ram")
    debug_ram = stack_check = ""
    stack_top = "ORIGIN(ram) + LENGTH(ram)"
    if dbg:
        size = dbg["end"] - dbg["begin"]
        linear = 0x2000 + (dbg["begin"] // 128) * 80 + dbg["begin"] % 128 - 0x20
        if linear + size == 0x2000 + ram:
            debug_ram = f"""
/* An in-circuit debugger keeps its own data in the last {size} bytes of RAM
 * ({dbg['begin']:#x}-{dbg['end'] - 1:#x}). A program linked for one (-mdebugger, which defines
 * __debugger) stays below them. */
__debugger_ram = DEFINED(__debugger) ? {size} : 0;
"""
            stack_top = "ORIGIN(ram) + LENGTH(ram) - __debugger_ram"
            stack_check = ('  ASSERT(__debugger_ram == 0 || __isr_stack_top <= __stack_top, '
                           '"the program\'s variables reach into the RAM kept for the debugger")\n')
    text = f"""/* Linker script for the {name}.
 * Generated by tools/devdb/gen_toolchain.py from {src['pack']} {src['version']},
 * {src['file']}. Do not edit.
 *
 * Address spaces:
 *   0x000000 up   program memory, as byte addresses (two per 14-bit word)
 *   0x802000 up   RAM in the linear view the FSR registers use
 *   0x808000 up   flash read as data through an FSR, one byte per word
 */
/* Library variant: banks{banks} */
OUTPUT_FORMAT("elf32-pic16f1")
ENTRY(_start)

MEMORY
{{
  flash    (rx) : ORIGIN = 0x000000, LENGTH = {words * 2:#x}
  ram      (rw) : ORIGIN = 0x802000, LENGTH = {ram}
  flashdat (r)  : ORIGIN = 0x808000, LENGTH = {words:#x}
  config   (r)  : ORIGIN = {cfg0 * 2:#x}, LENGTH = {ncfg * 2}{extra_regions}
}}

{debug_ram}
/* Bytes of stack for the interrupt handler, if there is one. */
PROVIDE(__isr_stack_size = 32);
/* Bytes kept for the main stack when a heap is in use. */
PROVIDE(__stack_size = {stack});

SECTIONS
{{
  /* Reset vector at word 0, interrupt vector at word 4. */
  .reset 0x0 : {{ KEEP(*(.reset)) }} > flash
  .isr 0x8 : {{ KEEP(*(.isr)) }} > flash
  /* Startup code first, in the order of its pieces (see crt0.S). */
  .text :
  {{
    KEEP(*(.init0)) KEEP(*(.init4)) KEEP(*(.init5)) KEEP(*(.init6))
    KEEP(*(.init9))
    *(.text .text.*)
  }} > flash
  __text_end = .;

  /* Constants follow the code in flash. Their addresses are in the FSR
   * view: 0x8000 plus the word address, one byte in each word. */
  .rodata (ORIGIN(flashdat) + (__text_end + 1) / 2) :
  {{
    *(.rodata .rodata.*)
  }} > flashdat

  /* Variables that have a fixed address in place of a stack frame, and
   * the stack pointer cell. Like stack variables they have no initial
   * value, so startup skips them. They come first in RAM, the runtime
   * library's before the rest: that library is built once, with the bank
   * selection of a 32-bank device, and must find its variables in the
   * first 32 banks of a larger one too. */
  .noinit (NOLOAD) :
  {{
    /* The stack pointer cell comes first of all, at a fixed address:
     * debug information that cannot hold a relocation names it. */
    *(.noinit.__sp)
    *libpicrt*.a:*(.noinit .noinit.*)
    *(.noinit .noinit.*)
  }} > ram

  .data :
  {{
    __data_start = .;
    *(.data .data.*)
    __data_end = .;
  }} > ram AT> flashdat
  __data_load_start = LOADADDR(.data);
  __data_size = SIZEOF(.data);

  .bss (NOLOAD) :
  {{
    __bss_start = .;
    *(.bss .bss.*)
    *(COMMON)
    __bss_end = .;
  }} > ram
  __bss_size = SIZEOF(.bss);

  .isr_stack (NOLOAD) :
  {{
    . += (SIZEOF(.isr) > 0) ? __isr_stack_size : 0;
    __isr_stack_top = .;
  }} > ram

  /* The main stack grows down from the end of RAM. */
  __stack_top = {stack_top};
{stack_check}
  /* malloc, if the program uses it, takes the RAM between the data and the
   * space set aside for the stack. Nothing enforces the boundary. */
  __heap_start = .;
  __heap_end = __stack_top - __stack_size;

  .config : {{ KEEP(*(.config)) }} > config
{extra_sections}
  __flash_words_used = (__text_end + 1) / 2 + SIZEOF(.rodata) + SIZEOF(.data);
  ASSERT(__flash_words_used <= {words}, "program does not fit in flash")

  /* Code compiled with -mcmodel=small never sets PCLATH, which is right
   * only if all code lies in the first page. Such code refers to
   * __pic16f1_one_page. */
  PROVIDE(__pic16f1_one_page = 1);
  ASSERT(DEFINED(__pic16f1_one_page) ? __text_end <= 0x1000 : 1,
         "code compiled with -mcmodel=small, but the program is larger than one page (2K words)")

  /DISCARD/ : {{ *(.note.GNU-stack) *(.comment) *(.eh_frame) *(.llvm_addrsig) }}
}}
"""
    with open(path, "w") as f:
        f.write(text)


def main():
    dev = json.load(open(sys.argv[1]))
    lower = dev["name"].lower()
    gen_header(dev, os.path.join(sys.argv[2], lower + ".h"))
    gen_ldscript(dev, os.path.join(sys.argv[3], lower + ".ld"))
    gen_config_table(dev, os.path.join(sys.argv[3], lower + ".cfg"))
    print(f"{dev['name']}: wrote {lower}.h, {lower}.ld and {lower}.cfg")


if __name__ == "__main__":
    main()
