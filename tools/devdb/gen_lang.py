#!/usr/bin/env python3
"""Generate a device's register definitions for Rust and for Zig.

Usage: gen_lang.py <devices/NAME.json> <rust-dir> <zig-dir>
Writes <rust-dir>/<name>.rs, a module of the pic16f1 crate, and
<zig-dir>/<name>.zig. Every address and bit position comes from the device
database, as for the C header (gen_toolchain.py).
"""
import json
import os
import re
import sys

RUST_KEYWORDS = {"as", "break", "const", "continue", "crate", "else", "enum", "extern",
                 "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod",
                 "move", "mut", "pub", "ref", "return", "self", "Self", "static", "struct",
                 "super", "trait", "true", "type", "unsafe", "use", "where", "while",
                 "async", "await", "dyn", "abstract", "become", "box", "do", "final",
                 "macro", "override", "priv", "typeof", "unsized", "virtual", "yield", "try"}


def ident(name):
    return re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name) is not None


def fields_of(sfr, sfr_names):
    """The register's fields without overlapping alternative names, in bit
    order."""
    out, bit = [], 0
    for f in sorted((f for f in sfr["fields"] if ident(f["name"]) and f["name"] not in sfr_names),
                    key=lambda f: f["bit"]):
        if f["bit"] < bit:
            continue
        out.append(f)
        bit = f["bit"] + f["width"]
    return out


def header(dev, comment):
    src = dev["source"]
    lines = [f"{comment} {dev['name']} special function registers.",
             f"{comment} Generated by tools/devdb/gen_lang.py from {src['pack']} {src['version']},",
             f"{comment} {src['file']}. Do not edit."]
    if src.get("imaginary"):
        lines.append(f"{comment} {src['imaginary']}")
    return lines


def gen_rust(dev, path):
    sfr_names = {s["name"] for s in dev["sfrs"]} | {j["name"] for j in dev["joined_sfrs"]}
    out = header(dev, "//!")
    out += ["//!",
            "//! A register is a constant: `LATE.write(3)`, `PORTB.read()`. Its fields are",
            "//! in a module named after it in lower case: `intcon::GIE.set()`,",
            "//! `adcon0::CHS.write(4)`, `pir1::TXIF.is_set()`.",
            "#![allow(non_upper_case_globals, non_snake_case, dead_code)]",
            "use crate::reg::{Reg16, Reg8};",
            ""]
    for s in dev["sfrs"]:
        if ident(s["name"]):
            out.append(f"pub const {s['name']}: Reg8 = Reg8::at(0x{s['addr']:03X});")
    out += ["", "// 16-bit register pairs, low byte first."]
    for j in dev["joined_sfrs"]:
        if ident(j["name"]) and j["width"] == 16:
            out.append(f"pub const {j['name']}: Reg16 = Reg16::at(0x{j['addr']:03X});")
    for s in dev["sfrs"]:
        fields = fields_of(s, sfr_names)
        if not fields or not ident(s["name"]):
            continue
        mod = s["name"].lower()
        if mod in RUST_KEYWORDS:
            mod = "r#" + mod
        out += ["", f"pub mod {mod} {{", "    use crate::reg::{Field, Reg8};"]
        for f in fields:
            name = f["name"] if f["name"] not in RUST_KEYWORDS else "r#" + f["name"]
            out.append(f"    pub const {name}: Field = "
                       f"Field::new(Reg8::at(0x{s['addr']:03X}), {f['bit']}, {f['width']});")
        out.append("}")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")


def gen_zig(dev, path):
    sfr_names = {s["name"] for s in dev["sfrs"]} | {j["name"] for j in dev["joined_sfrs"]}
    out = header(dev, "//!")
    out += ["//!",
            "//! A register is a pointer: `LATE.* = 3;`, `const v = PORTB.*;`. Its fields",
            "//! are a packed struct at the same address, named with `bits` as in the C",
            "//! header: `INTCONbits.GIE = 1;`, `ADCON0bits.CHS = 4;`.",
            ""]
    for s in dev["sfrs"]:
        if ident(s["name"]):
            out.append(f"pub const {s['name']}: *volatile u8 = @ptrFromInt(0x{s['addr']:03X});")
    out += ["", "// 16-bit register pairs, low byte first."]
    for j in dev["joined_sfrs"]:
        if ident(j["name"]) and j["width"] == 16:
            out.append(f"pub const {j['name']}: *align(1) volatile u16 = @ptrFromInt(0x{j['addr']:03X});")
    for s in dev["sfrs"]:
        fields = fields_of(s, sfr_names)
        if not fields or not ident(s["name"]):
            continue
        out += ["", f"pub const {s['name']}bits: *volatile packed struct(u8) {{"]
        bit, pad = 0, 0
        for f in fields:
            if f["bit"] > bit:
                out.append(f"    _{pad}: u{f['bit'] - bit} = 0,")
                pad += 1
            out.append(f"    {zig_name(f['name'])}: u{f['width']},")
            bit = f["bit"] + f["width"]
        if bit < 8:
            out.append(f"    _{pad}: u{8 - bit} = 0,")
        out.append(f"}} = @ptrFromInt(0x{s['addr']:03X});")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")


ZIG_KEYWORDS = {"align", "and", "anyframe", "anytype", "asm", "break", "callconv", "catch",
                "comptime", "const", "continue", "defer", "else", "enum", "errdefer", "error",
                "export", "extern", "fn", "for", "if", "inline", "noalias", "nosuspend",
                "opaque", "or", "orelse", "packed", "pub", "resume", "return", "struct",
                "suspend", "switch", "test", "threadlocal", "try", "union", "unreachable",
                "var", "volatile", "while", "type", "void", "bool", "true", "false", "null",
                "undefined"}


def zig_name(name):
    return f'@"{name}"' if name in ZIG_KEYWORDS else name


def main():
    dev = json.load(open(sys.argv[1]))
    lower = dev["name"].lower()
    gen_rust(dev, os.path.join(sys.argv[2], lower + ".rs"))
    gen_zig(dev, os.path.join(sys.argv[3], lower + ".zig"))
    print(f"{dev['name']}: wrote {lower}.rs and {lower}.zig")


if __name__ == "__main__":
    main()
