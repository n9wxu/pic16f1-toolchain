#!/usr/bin/env python3
"""Write a CMSIS-SVD description of a device's registers, for the peripheral
views of debugger front ends (VS Code's Peripheral Viewer, for one).

    gen_svd.py devices/pic16f1937.json toolchain/svd

Addresses are the debugger's (docs/spec/debug-interface.md): data memory
address + 0x800000. The device data has no grouping of registers into
peripherals, so they are grouped here by name.
"""
import json
import os
import re
import sys
from xml.sax.saxutils import escape

DATA_BASE = 0x800000

# First match wins. \1 in the group name is the pattern's first group.
GROUPS = [
    (r"(INDF\d|PCL|STATUS|FSR\d[LH]|BSR|WREG|PCLATH|INTCON|STKPTR|TOS[LH]|.*_SHAD)$", "CPU", "Core registers"),
    (r"(?:PORT|LAT|TRIS|ANSEL|WPU|ODCON|SLRCON|INLVL)([A-G])$", r"PORT\1", r"Port \1"),
    (r"IOC([A-G])[PNF]$", r"PORT\1", r"Port \1"),
    (r"(PIR|PIE)\d+$", "INTERRUPTS", "Interrupt flags and enables"),
    (r"(OPTION_REG|PCON\d?|WDTCON\d?|BORCON|APFCON\d?|VREGCON)$", "SYSTEM", "Reset, watchdog and pin options"),
    (r"(OSC.*|CLK.*)$", "OSCILLATOR", "Oscillator"),
    (r"TMR0[LH]?$|T0CON\d?$", "TIMER0", "Timer 0"),
    (r"(?:TMR|PR)(\d)[LH]?$", r"TIMER\1", r"Timer \1"),
    (r"T(\d)(?:CON|GCON|HLT|RST|CLKCON|GATE|CLK)$", r"TIMER\1", r"Timer \1"),
    (r"(ADRES[LH]?|ADCON\d|ADACT|ADC.*)$", "ADC", "Analog-to-digital converter"),
    (r"(CM\d?CON\d?|CM\dN?[NP]SEL|CMOUT|CMSTAT)$", "COMPARATORS", "Comparators"),
    (r"(FVRCON|DAC.*|SRCON\d)$", "REFERENCES", "Voltage reference, DAC and SR latch"),
    (r"(EE.*|PM.*|NVM.*)$", "NVM", "Flash and EEPROM access"),
    (r"(RC\d?REG|TX\d?REG|SP\d?BRG[LH]?|RC\d?STA|TX\d?STA|BAUD\d?CON)$", "EUSART", "EUSART"),
    (r"SSP\d?.*$", "MSSP", "Synchronous serial port"),
    (r"(CCP.*|PWM.*|PSTR.*|ECCP.*)$", "CCP", "Capture, compare and PWM"),
    (r"CPS.*$", "CAPSENSE", "Capacitive sensing"),
    (r"LCD.*$", "LCD", "LCD driver"),
    (r".*PPS$|PPSLOCK$", "PPS", "Peripheral pin select"),
]


def group_of(name):
    for pattern, group, text in GROUPS:
        m = re.match(pattern, name)
        if m:
            return m.expand(group), m.expand(text)
    return "OTHER", "Other registers"


def main():
    dev = json.load(open(sys.argv[1]))
    name = dev["name"]
    groups = {}
    for s in dev["sfrs"]:
        if not re.fullmatch(r"[A-Za-z_]\w*", s["name"]):
            continue
        g, text = group_of(s["name"])
        groups.setdefault(g, (text, []))[1].append(s)
    src = dev["source"]
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           f"<!-- {name} registers for a debugger's peripheral view. Generated by",
           f"     tools/devdb/gen_svd.py from {escape(src['pack'])} {escape(src['version'])}. Do not edit.",
           "     Addresses are the debugger's: data memory address + 0x800000. -->",
           '<device schemaVersion="1.3" xmlns:xs="http://www.w3.org/2001/XMLSchema-instance">',
           f"  <name>{name}</name>", "  <version>1.0</version>",
           f"  <description>{name} special function registers</description>",
           "  <addressUnitBits>8</addressUnitBits>", "  <width>8</width>",
           "  <size>8</size>", "  <access>read-write</access>",
           "  <resetValue>0</resetValue>", "  <resetMask>0</resetMask>",
           "  <peripherals>"]
    order = ["CPU"] + sorted(g for g in groups if g not in ("CPU", "OTHER")) + ["OTHER"]
    for g in order:
        if g not in groups:
            continue
        text, regs = groups[g]
        regs.sort(key=lambda s: s["addr"])
        base = DATA_BASE + regs[0]["addr"]
        out += ["    <peripheral>", f"      <name>{g}</name>", f"      <description>{escape(text)}</description>",
                f"      <baseAddress>{base:#x}</baseAddress>",
                f"      <addressBlock><offset>0</offset><size>{regs[-1]['addr'] - regs[0]['addr'] + 1:#x}</size>"
                "<usage>registers</usage></addressBlock>",
                "      <registers>"]
        for s in regs:
            out += ["        <register>", f"          <name>{s['name']}</name>",
                    f"          <description>{s['name']}, data address {s['addr']:#05x}</description>",
                    f"          <addressOffset>{DATA_BASE + s['addr'] - base:#x}</addressOffset>",
                    "          <size>8</size>",
                    f"          <resetValue>{s['por']:#x}</resetValue>",
                    f"          <resetMask>{s['por_known']:#x}</resetMask>"]
            fields, used = [], 0
            for f in sorted(s["fields"], key=lambda f: f["bit"]):
                mask = ((1 << f["width"]) - 1) << f["bit"]
                # Alternative names for the same bits are left out.
                if mask & used or not re.fullmatch(r"[A-Za-z_]\w*", f["name"]):
                    continue
                used |= mask
                fields.append(f)
            if fields:
                out.append("          <fields>")
                for f in fields:
                    out.append(f"            <field><name>{f['name']}</name><bitOffset>{f['bit']}</bitOffset>"
                               f"<bitWidth>{f['width']}</bitWidth></field>")
                out.append("          </fields>")
            out.append("        </register>")
        out += ["      </registers>", "    </peripheral>"]
    out += ["  </peripherals>", "</device>", ""]
    path = os.path.join(sys.argv[2], name.lower() + ".svd")
    os.makedirs(sys.argv[2], exist_ok=True)
    with open(path, "w") as f:
        f.write("\n".join(out))
    print(f"{name}: wrote {path} ({sum(len(v[1]) for v in groups.values())} registers in {len(groups)} groups)")


if __name__ == "__main__":
    main()
